// Category — вид находки.
type Category int

const (
	// CatShtamp — пустые обороты и штампы: «играет ключевую роль»,
	// «стоит отметить», «в современном мире».
	CatShtamp Category = iota
	// CatKancelyarit — канцелярит: «осуществляется», «в рамках», «данный».
	CatKancelyarit
	// CatOcenka — оценки без меры: «эффективный», «значительный».
	CatOcenka
	// CatCepochka — цепочка отглагольных существительных.
	CatCepochka
	// CatZhargon — офисный жаргон и кальки: «стейкхолдер», «синк», «импакт».
	CatZhargon
)

// Title — название категории по-русски.
func (c Category) Title() string {
	switch c {
	case CatShtamp:
		return "штампы и пустые обороты"
	case CatKancelyarit:
		return "канцелярит"
	case CatOcenka:
		return "оценки без меры"
	case CatCepochka:
		return "цепочки отглагольных существительных"
	case CatZhargon:
		return "офисный жаргон и кальки"
	}
	return "?"
}

// weight — вклад находки в оценку.
func (c Category) weight() float64 {
	switch c {
	case CatShtamp:
		return 3
	case CatKancelyarit:
		return 2
	case CatOcenka:
		return 1
	case CatCepochka:
		return 2
	case CatZhargon:
		return 2
	}
	return 1
}

